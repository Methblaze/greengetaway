// Inlines Leaflet's stylesheet into a JS module, so the web build carries the
// map's CSS with it instead of depending on a CDN at runtime.
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const css = fs.readFileSync(path.join(root, "node_modules/leaflet/dist/leaflet.css"), "utf8");
const out = path.join(root, "src/web/leafletCss.js");
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, "// Generated by scripts/make-leaflet-css.js. Do not edit.\nexport default " + JSON.stringify(css) + ";\n");
console.log("wrote", path.relative(root, out), css.length, "chars");
